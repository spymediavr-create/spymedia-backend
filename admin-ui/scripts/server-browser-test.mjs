import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import http from 'node:http';
import crypto from 'node:crypto';
import {createRequire} from 'node:module';
import assert from 'node:assert/strict';
import {config} from '../backend/config.cjs';
import {Service} from '../backend/service.cjs';
import {createAdminHandler} from '../server-core.cjs';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const dir=await fs.mkdtemp(path.join(os.tmpdir(),'spymedia-browser-test-'));
const settings=config({...process.env,SNS_DATA_DIR:dir,SNS_STORAGE_PERSISTENCE:'confirmed',SNS_SINGLE_INSTANCE:'confirmed',SNS_PUBLISH_ENABLED:'true'});
let mockPublications=0;
const connectors={availability:()=>({instagram:true,facebook:true,x:false,youtube:false,blog:true}),publish:async(job,ctx)=>{mockPublications++;await ctx.beforePublication({});return {externalId:'local-fixture-'+job.channel};}};
const service=new Service({settings,connectors});
const salt=crypto.randomBytes(16),password=crypto.randomBytes(32).toString('hex');
const passwordHash=salt.toString('hex')+':'+crypto.scryptSync(password,salt,64).toString('hex');
const handler=createAdminHandler({mode:'authenticated',username:'local-fixture',passwordHash,service});
const server=http.createServer((req,res)=>handler(req,res).then(handled=>{if(!handled){res.writeHead(404);res.end();}}));
await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
const origin='http://127.0.0.1:'+server.address().port;
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1100}});
const errors=[],external=[];page.on('pageerror',e=>errors.push(e.message));
page.on('request',req=>{if(!req.url().startsWith(origin)&&!req.url().startsWith('blob:'+origin)&&!req.url().startsWith('data:'))external.push(req.url());});
try {
  await page.goto(origin+'/admin/login');await page.waitForFunction(()=>!document.getElementById('login-submit').disabled);
  await page.fill('#login-id','local-fixture');await page.fill('#login-password',password);await page.click('#login-submit');await page.waitForURL(origin+'/admin');
  await page.waitForFunction(()=>!document.getElementById('prepare-server').disabled);assert.equal(await page.locator('#server-workflow').isVisible(),true);console.log('PASS real session enables authenticated workflow');
  await page.fill('#title','제주 풍경 테스트');await page.fill('#description','로컬 합성 자료와 모의 API 검증용 설명');
  await page.locator('#image-input').setInputFiles(path.resolve('admin-ui/test-results/test-coast.png'));
  await page.click('#prepare-server');
  await page.waitForFunction(()=>document.querySelectorAll('#server-jobs .job-card').length===2&&[...document.querySelectorAll('#server-jobs input')].every(e=>!e.disabled),{timeout:45000});
  assert.equal(mockPublications,0);console.log('PASS authenticated upload and real conversion prepare two channels without publication');
  await page.locator('#server-jobs input').nth(0).check();await page.locator('#server-jobs input').nth(1).check();
  page.once('dialog',dialog=>dialog.accept());await page.click('#start-server');
  await page.waitForFunction(()=>[...document.querySelectorAll('#server-jobs strong')].filter(e=>e.textContent.includes('완료')).length===2,{timeout:30000});
  assert.equal(mockPublications,2);console.log('PASS approved local fixture uses mocked connectors and records verified results');
  await page.click('#prepare-server');await page.waitForFunction(()=>document.getElementById('server-feedback').textContent.includes('준비한 작업'));
  assert.equal(mockPublications,2);assert.equal(await page.locator('#server-jobs .job-card').count(),2);console.log('PASS repeated preparation cannot duplicate completed publications');
  await page.screenshot({path:path.resolve('admin-ui/test-results/admin-server.png'),fullPage:true});
  await page.click('#logout-button');await page.waitForURL(origin+'/admin/login');
  assert.equal((await page.request.get(origin+'/api/admin/jobs')).status(),401);console.log('PASS logout revokes authenticated API access');
  assert.deepEqual(errors,[]);assert.deepEqual(external,[]);console.log('PASS no browser errors or external API requests');
}finally{
  await browser.close();await new Promise(resolve=>server.close(resolve));
  assert.equal(path.dirname(path.resolve(dir)),path.resolve(os.tmpdir()));await fs.rm(dir,{recursive:true,force:true});
}
